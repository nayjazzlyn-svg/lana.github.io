function buildPgHTML(c, t, tot, s, e, pFn, sFn, ps) {
  if (!tot) return '';
  var h = '<div class="pagination-bar"><div class="pagination-info">Menampilkan <strong>' + s + '-' + e + '</strong> dari <strong>' + tot + '</strong></div><div style="display:flex;align-items:center;gap:12px;flex-wrap:wrap"><div style="display:flex;align-items:center;gap:6px;font-size:.76rem;color:var(--muted)">Tampil:<select class="pg-size-select" onchange="' + sFn + '(parseInt(this.value))">';
  [10, 15, 25, 50].forEach(function (v) {
    h += '<option value="' + v + '"' + (v === ps ? ' selected' : '') + '>' + v + '</option>';
  });
  h += '</select></div><div class="pagination-controls"><button class="pg-btn" onclick="' + pFn + '(' + (c - 1) + ')"' + (c <= 1 ? ' disabled' : '') + '><svg viewBox="0 0 24 24"><polyline points="15 18 9 12 15 6"/></svg></button>';
  pgNums(c, t).forEach(function (p) {
    if (p === '...') h += '<span class="pg-ellipsis">...</span>';
    else h += '<button class="pg-btn' + (p === c ? ' active' : '') + '" onclick="' + pFn + '(' + p + ')">' + p + '</button>';
  });
  h += '<button class="pg-btn" onclick="' + pFn + '(' + (c + 1) + ')"' + (c >= t ? ' disabled' : '') + '><svg viewBox="0 0 24 24"><polyline points="9 18 15 12 9 6"/></svg></button></div></div></div>';
  return h;
}
function pgNums(c, t) {
  if (t <= 7) {
    var a = [];
    for (var i = 1; i <= t; i++) a.push(i);
    return a;
  }
  var p = [1];
  if (c > 3) p.push('...');
  for (var j = Math.max(2, c - 1); j <= Math.min(t - 1, c + 1); j++) p.push(j);
  if (c < t - 2) p.push('...');
  p.push(t);
  return p;
}
