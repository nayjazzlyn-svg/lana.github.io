function compressImageFile(file, maxW, quality) {
  return new Promise(function (resolve, reject) {
    var reader = new FileReader();
    reader.onload = function (ev) {
      var img = new Image();
      img.onload = function () {
        var canvas = document.createElement('canvas');
        var w = img.width, h = img.height;
        if (w > maxW) {
          h = Math.round(h * maxW / w);
          w = maxW;
        }
        canvas.width = w;
        canvas.height = h;
        canvas.getContext('2d').drawImage(img, 0, 0, w, h);
        var result = canvas.toDataURL('image/jpeg', quality);
        if (result.length > 48000 && quality > 0.2) {
          result = canvas.toDataURL('image/jpeg', 0.2);
        }
        if (result.length > 48000 && maxW > 400) {
          var w2 = Math.round(w * 0.6);
          var h2 = Math.round(h * 0.6);
          canvas.width = w2;
          canvas.height = h2;
          canvas.getContext('2d').drawImage(img, 0, 0, w2, h2);
          result = canvas.toDataURL('image/jpeg', 0.35);
        }
        resolve(result);
      };
      img.onerror = reject;
      img.src = ev.target.result;
    };
    reader.onerror = reject;
    reader.readAsDataURL(file);
  });
}
