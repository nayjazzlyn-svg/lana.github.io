function convertDriveLink(url) {
  if (!url) return '';
  var match = url.match(/drive\.google\.com\/file\/d\/([a-zA-Z0-9_-]+)/);
  if (match && match[1]) {
    return 'https://drive.google.com/uc?export=view&id=' + match[1];
  }
  var match2 = url.match(/drive\.google\.com\/open\?id=([a-zA-Z0-9_-]+)/);
  if (match2 && match2[1]) {
    return 'https://drive.google.com/uc?export=view&id=' + match2[1];
  }
  return url;
}
function handleProjectFotoUpload(input, mode) {
  var file = input.files[0];
  if (!file) return;
  if (file.size > 5 * 1024 * 1024) {
    toast('Ukuran foto terlalu besar (maks 5MB)', 'error');
    input.value = '';
    return;
  }
  var px = mode === 'add' ? 'p' : 'ep';
  var placeholder = document.getElementById(px + 'Placeholder');
  var previewWrap = document.getElementById(px + 'PreviewWrap');
  placeholder.innerHTML = '<div class="spinner"></div>';
  placeholder.style.display = '';
  previewWrap.style.display = 'none';
  compressImageFile(file, 800, 0.45).then(function (b64) {
    if (b64.length > 48000) {
      toast('Foto terlalu besar setelah kompresi', 'error');
      placeholder.innerHTML = buildUploadPlaceholderHTML(px);
      previewWrap.style.display = 'none';
      input.value = '';
      return;
    }
    if (mode === 'add') {
      projectFotoBase64 = b64;
    } else {
      editProjectFotoBase64 = b64;
    }
    showProjectFotoPreview(px, b64);
    toast('Foto berhasil diunggah', 'success');
  }).catch(function () {
    toast('Gagal memproses gambar', 'error');
    placeholder.innerHTML = buildUploadPlaceholderHTML(px);
  });
  input.value = '';
}
